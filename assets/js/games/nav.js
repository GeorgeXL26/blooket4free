function renderSidebar(activeId) {
    const nav = document.getElementById("sidebar");
    if (!nav) return;

    const items = NAV_ITEMS.map((item) => `
        <li>
            <a class="Sidebar_link__pbkfx${item.id === activeId ? " active" : ""}" href="${item.href}">
                <span class="Sidebar_listIcon__rg5X6">
                    <svg aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg"
                        viewBox="${item.viewBox}">
                        <path fill="currentColor" d="${item.path}"></path>
                    </svg>
                </span>
                <span class="Sidebar_text__TwkTk">${item.label}</span>
            </a>
        </li>`).join("");

    nav.innerHTML = `
        <img alt="Blooket" loading="lazy" width="168" decoding="async" class="Sidebar_logoDesktop__NeFcd"
            src="./assets/misc_images/logo.png">
        <ul class="Sidebar_list__ljw79">${items}</ul>`;
}

function wireShell() {
    const hamburgerBtn = document.getElementById("hamburgerBtn");
    const sidebar = document.getElementById("sidebar");
    const overlay = document.getElementById("overlay");

    if (hamburgerBtn && sidebar) {
        hamburgerBtn.addEventListener("click", () => {
            sidebar.classList.add("active");
            if (overlay) overlay.classList.add("active");
        });
    }
    if (overlay && sidebar) {
        overlay.addEventListener("click", () => {
            sidebar.classList.remove("active");
            overlay.classList.remove("active");
        });
    }

    const amount = document.getElementById("coinAmount");
    if (amount && typeof getCoins === "function") {
        const paint = (coins) => {
            amount.innerText = (coins ?? getCoins()).toLocaleString();
        };
        paint();
        if (typeof onCoinsChanged === "function") onCoinsChanged(paint);
    }
}

document.addEventListener("DOMContentLoaded", () => {
    wireShell();
});
